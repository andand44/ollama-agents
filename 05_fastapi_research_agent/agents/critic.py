"""
Агент-Критик: находит проблемы в тексте.
Возвращает структурированный список замечаний.
"""

from utils import call_llm, debug_log


CRITIC_SYSTEM_PROMPT = """Ты — строгий редактор-критик. Твоя задача — найти проблемы в тексте пользователя.

ПРАВИЛА:
1. Анализируй текст по критериям:
   - Ясность: есть ли непонятные предложения?
   - Структура: логичен ли порядок мыслей?
   - Стиль: есть ли канцеляризмы, повторы, «вода»?
   - Факты: есть ли утверждения, требующие проверки?

2. НЕ переписывай текст. Только указывай на проблемы.

3. Формат ответа — строгий список:
   • Проблема 1: [краткое описание]
   • Проблема 2: [краткое описание]

4. Максимум 5 проблем. Отмечай только самое важное.

5. Если проблем нет — напиши: «Текст хороший, серьёзных проблем не найдено».

Отвечай на русском языке."""


def criticize(text: str) -> str:
    """Запускает агента-Критика на тексте. Возвращает список проблем."""
    debug_log("CRITIC", f"Анализ текста ({len(text)} символов)")

    user_prompt = f"Проанализируй текст:\n\n---\n{text}\n---"
    result = call_llm(CRITIC_SYSTEM_PROMPT, user_prompt)

    debug_log("CRITIC", f"Найдено проблем: {_count_problems(result)}")
    return result


def _count_problems(text: str) -> int:
    """Считает проблемы в ответе критика (строки, начинающиеся с '•')."""
    return sum(1 for line in text.splitlines() if line.strip().startswith('•'))