"""
Агент-Судья: даёт финальную оценку работе всей цепочки.
Сравнивает оригинал и улучшенный текст, оценивает изменения.
"""

from utils import call_llm, debug_log


JUDGE_SYSTEM_PROMPT = """Ты — судья. Даёшь КРАТКИЙ финальный вердикт.

ФОРМАТ (строго, максимум 6 строк):
ОЦЕНКА: X/5
СИЛЬНЫЕ СТОРОНЫ: [одно предложение]
ОСТАЛОСЬ ПРОБЛЕМ: [одно предложение]
РЕКОМЕНДАЦИЯ: [одно предложение]

ПРАВИЛА:
1. НЕ разбирай каждый пункт отдельно. Только общий итог.
2. Оценка 1-5: 5 = отлично, 1 = плохо.
3. Если в улучшенном тексте есть цифры без источника — снижай оценку.
4. Максимум 6 строк. Больше — ошибка.

Отвечай на русском."""


def judge(original: str, critique: str, improved: str, fact_report: dict) -> str:
    """Выносит финальный вердикт по всей цепочке обработки."""
    debug_log("JUDGE", "Анализ результатов всей цепочки")

    facts_text = fact_report.get('report', 'Факт-чек не проводился')

    user_prompt = (
        f"ОРИГИНАЛ:\n{original}\n\n"
        f"ЗАМЕЧАНИЯ КРИТИКА:\n{critique}\n\n"
        f"УЛУЧШЕННЫЙ ТЕКСТ:\n{improved}\n\n"
        f"ОТЧЁТ ФАКТ-ЧЕКЕРА:\n{facts_text}\n\n"
        "Дай финальную оценку работы цепочки."
    )

    result = call_llm(JUDGE_SYSTEM_PROMPT, user_prompt)
    debug_log("JUDGE", f"Вердикт получен ({len(result)} символов)")
    return result